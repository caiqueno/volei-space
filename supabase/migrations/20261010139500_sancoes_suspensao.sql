-- Registro da suspensão automática. A súmula decide o cumprimento pelas
-- ocorrências, então a regra vale mesmo antes desta tabela existir.
-- Não apaga linha. Não concede a anon nem a authenticated. Não foi aplicada.

create table if not exists public."SuspensaoAtleta" (
  id bigint generated by default as identity primary key,
  "ligaId" integer not null,
  "categoriaCampeonatoId" uuid,
  "jogadorId" integer not null,
  "equipeId" integer,
  "partidaOrigemId" integer,
  motivo text not null,
  "jogosRestantes" integer not null default 1,
  "criadoEm" timestamptz not null default now()
);

create index if not exists "SuspensaoAtleta_jogador_idx" on public."SuspensaoAtleta" ("jogadorId", "categoriaCampeonatoId");

alter table public."SuspensaoAtleta" enable row level security;
revoke all on table public."SuspensaoAtleta" from public, anon, authenticated;
grant all on table public."SuspensaoAtleta" to service_role;

do $$
declare seq text;
begin
  seq := pg_get_serial_sequence('public."SuspensaoAtleta"', 'id');
  if seq is not null then
    execute format('revoke all on sequence %s from public, anon, authenticated', seq);
    execute format('grant all on sequence %s to service_role', seq);
  end if;
end $$;
